func TestCountOracleIgnoresSubtests(t *testing.T) {
	// Go indents subtest result lines; only top-level TestCFFDRS* functions are
	// the fifteen-or-so the docs and the gate talk about.
	out := `=== RUN   TestCFFDRSBuildupEffect
--- SKIP: TestCFFDRSBuildupEffect (0.00s)
=== RUN   TestCFFDRSSurfaceROS
=== RUN   TestCFFDRSSurfaceROS/C1
    --- SKIP: TestCFFDRSSurfaceROS/C1 (0.00s)
--- PASS: TestCFFDRSSurfaceROS (0.31s)
=== RUN   TestSomethingElse
--- PASS: TestSomethingElse (0.00s)
PASS
`
	total, skipped := countOracle(out)
	if total != 2 {
		t.Errorf("total = %d, want 2 (subtests and non-oracle tests must not count)", total)
	}
	if skipped != 1 {
		t.Errorf("skipped = %d, want 1 (the indented subtest skip must not count)", skipped)
	}
}

